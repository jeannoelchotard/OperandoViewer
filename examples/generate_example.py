#!/usr/bin/env python3
"""Generates a small SYNTHETIC operando dataset (no real measurement) to try the viewer:

  examples/synthetic_series/scan_001.xy ... scan_060.xy   diffraction patterns
  examples/synthetic_series.buf                           list of the patterns (for "From a .buf file")
  examples/synthetic_echem.csv                            charge/discharge curve (for "Load .csv")

Run:  python examples/generate_example.py
"""
import os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "synthetic_series")
N_FRAMES, N_POINTS = 60, 400
rng = np.random.default_rng(42)


def peak(x, center, height, width=0.22, eta=0.5):
    """Pseudo-Voigt profile."""
    u = (x - center) / width
    return height * (eta / (1 + u ** 2) + (1 - eta) * np.exp(-np.log(2) * u ** 2))


def main():
    os.makedirs(OUT, exist_ok=True)
    x = np.linspace(15, 45, N_POINTS)
    names = []
    for k in range(N_FRAMES):
        s = k / (N_FRAMES - 1)                      # 0 -> 1 over the experiment
        tri = 1 - abs(2 * s - 1)                    # 0 -> 1 -> 0 (charge then discharge)
        y = 30 + 8 * np.exp(-((x - 25) / 12) ** 2)  # smooth background
        y += peak(x, 20.0 + 0.7 * tri, 800)         # main phase: peak shifts during charge
        y += peak(x, 27.0, 500 * max(0.0, np.sin(np.pi * min(1.0, tri * 1.6))) ** 2)  # intermediate phase
        y += peak(x, 33.5 - 0.15 * tri, 120)        # weak peak
        y += peak(x, 38.4, 8000, width=0.12)        # very intense peak (e.g. current collector)
        y = rng.poisson(np.clip(y, 0, None)).astype(float)
        name = f"scan_{k + 1:03d}.xy"
        names.append(name)
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write("# synthetic pattern (generated by examples/generate_example.py)\n")
            f.write("# 2theta intensity\n")
            for xi, yi in zip(x, y):
                f.write(f"{xi:.4f} {yi:.1f}\n")

    with open(os.path.join(HERE, "synthetic_series.buf"), "w", encoding="utf-8") as f:
        f.write("\n".join(f"synthetic_series/{n}" for n in names) + "\n")

    # one full charge/discharge cycle over 10 h, 1 point every ~36 s
    n = 1000
    t = np.linspace(0, 36000, n)
    s = t / t[-1]
    tri = 1 - np.abs(2 * s - 1)
    voltage = 2.7 + 1.3 * tri ** 0.8 + 0.02 * np.sin(40 * np.pi * s)
    current = np.where(s < 0.5, 1.0, -1.0)
    charge = np.where(s < 0.5, 150 * (s / 0.5), 150.0)
    discharge = np.where(s < 0.5, 0.0, 140 * ((s - 0.5) / 0.5))
    with open(os.path.join(HERE, "synthetic_echem.csv"), "w", encoding="utf-8", newline="") as f:
        f.write("Index,Test_Time,Voltage,Current,Charge_Capacity_[mAh/g],Discharge_Capacity_[mAh/g]\n")
        for i in range(n):
            f.write(f"{i},{t[i]:.1f},{voltage[i]:.5f},{current[i]:.1f},{charge[i]:.3f},{discharge[i]:.3f}\n")
    print(f"{N_FRAMES} patterns + synthetic_series.buf + synthetic_echem.csv written in {HERE}")


if __name__ == "__main__":
    main()
